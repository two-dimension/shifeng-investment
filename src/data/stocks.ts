export function searchStocks(keyword: string, market: 'a' | 'hk' | 'us' | 'jp' | 'kr' = 'a') {
  let list: { code: string; name: string; market?: "sh" | "sz" }[] = [];
  if (market === 'hk') {
    list = HK_STOCK_LIST;
  } else if (market === 'us') {
    list = US_STOCK_LIST;
  } else if (market === 'jp') {
    list = JP_STOCK_LIST;
  } else if (market === 'kr') {
    list = KR_STOCK_LIST;
  } else {
    list = STOCK_LIST;
  }
  if (!keyword) return list.slice(0, 20).map((s) => ({ value: s.code, label: `${s.code} ${s.name}`, name: s.name, code: s.code }));
  const kw = keyword.toUpperCase();
  return list.filter((s) => s.code.includes(kw) || s.name.includes(keyword)).slice(0, 20).map((s) => ({ value: s.code, label: `${s.code} ${s.name}`, name: s.name, code: s.code }));
}

